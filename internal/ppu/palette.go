const (
	paletteColorCount        = 64
	emphasisCombinationCount = 8

	colorChannelRed   = 0
	colorChannelGreen = 1
	colorChannelBlue  = 2
	colorChannelAlpha = 3

	emphasisBitRed   = 0x01
	emphasisBitGreen = 0x02
	emphasisBitBlue  = 0x04

	tintNumerator   = 3
	tintDenominator = 4
	maxChannelValue = 0xFF
)

// PaletteTable contains the 64 RGBA colors for each of the 8 PPUMASK color emphasis combinations (0..7).
// PaletteTable[0] corresponds to normal rendering without any color emphasis.
var PaletteTable [emphasisCombinationCount][paletteColorCount]Color

func attenuateChannel(channel byte) byte {
	val := (uint32(channel) * tintNumerator) / tintDenominator
	if val > maxChannelValue {
		return byte(maxChannelValue)
	}
	return byte(val)
}

func init() {
	for e := range emphasisCombinationCount {
		empRed := (e & emphasisBitRed) != 0
		empGreen := (e & emphasisBitGreen) != 0
		empBlue := (e & emphasisBitBlue) != 0

		for c := range paletteColorCount {
			base := DefaultPalette[c]
			rVal := base[colorChannelRed]
			gVal := base[colorChannelGreen]
			bVal := base[colorChannelBlue]
			aVal := base[colorChannelAlpha]

			if empGreen || empBlue {
				rVal = attenuateChannel(rVal)
			}
			if empRed || empBlue {
				gVal = attenuateChannel(gVal)
			}
			if empRed || empGreen {
				bVal = attenuateChannel(bVal)
			}

			PaletteTable[e][c] = Color{rVal, gVal, bVal, aVal}
		}
	}
}
